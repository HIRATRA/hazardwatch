import { describe, expect, it } from "vitest";

import { isUuid } from "./uuid";

describe("isUuid", () => {
  it("accepts identifiers generated by PostgreSQL", () => {
    expect(isUuid("0b9c2f6e-5d1a-4c3e-9f7b-2a8d4e6c1f30")).toBe(true);
  });

  it.each(["", "new", "42", "0b9c2f6e-5d1a-4c3e-9f7b"])("rejects %j", (value) => {
    expect(isUuid(value)).toBe(false);
  });
});
